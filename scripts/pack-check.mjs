import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const packed = spawnSync('npm', ['pack', '--dry-run', '--json', '--ignore-scripts'], { encoding: 'utf8' });
assert.equal(packed.status, 0, packed.stderr);
const artifact = JSON.parse(packed.stdout)[0];
assert.equal(artifact.name, '@matuto-ai/opencode-broker-connector');
assert.equal(artifact.filename, `matuto-ai-opencode-broker-connector-${artifact.version}.tgz`);
const files = artifact.files.map(x => x.path);
for (const file of ['bin/doctor.mjs', 'src/capabilities.mjs', 'plugin/index.mjs', 'plugin/tui.mjs', 'src/installation.mjs', 'src/setup-ui.mjs', 'src/native-context.mjs', 'src/pending-resume.mjs', 'vendor/enrollment/approval.mjs', 'src/native-plugin.mjs', 'src/cooperative-inbox.mjs', 'vendor/broker/reference/inbox.mjs', 'vendor/broker/src/protocol.mjs', 'vendor/broker/LICENSE']) assert.ok(files.includes(file), `Missing ${file}`);
assert.equal(files.some(path => /(^|\/)(test|node_modules|\.github)(\/|$)|\.token$|\.sqlite$|connection\.json$/.test(path)), false);
console.log(`Verified ${files.length} packaged files; no tests, credentials or state.`);
